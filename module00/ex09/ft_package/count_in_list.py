def count_in_list(lst: list, item: str) -> int:
    """
    Counts how many times 'item' appears in 'lst'.

    Args:
        lst (list): The list to search.
        item (str): The item to count.

    Returns:
        int: The number of occurrences of 'item' in 'lst'.
    """
    return lst.count(item)
